import {randomUUID} from 'node:crypto';
import {mkdir, readFile, writeFile, rename, unlink, readdir} from 'node:fs/promises';
import {join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawn} from 'node:child_process';
import {FrameChangeAnalyzer} from './frame-analysis.js';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const COMMANDS = new Map([
  ['开始观察', 'start'], ['停止观察', 'stop'], ['观察状态', 'status'],
]);

// Only a local, bounded image sampler. No model, input hooks or memory writes.
export function createWatchCapture(root = ROOT) {
  return async ({directory, signal}) => {
    const scratch = join(directory, 'scratch');
    await mkdir(scratch, {recursive: true});
    try {
      const stdout = await new Promise((accept, reject) => {
        const child = spawn(join(root, '.venv/Scripts/python.exe'), [
          join(root, 'tools/coach_overlay/capture_once.py'), '--monitor', '1', '--outdir', scratch,
        ], {cwd: root, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe']});
        let output = '', errors = '', failed, timedOut = false;
        const abort = () => child.kill();
        const timer = setTimeout(() => { timedOut = true; child.kill(); }, 10000);
        signal.addEventListener('abort', abort, {once: true});
        if (signal.aborted) abort();
        child.stdout.on('data', chunk => { output += chunk; });
        child.stderr.on('data', chunk => { errors = (errors + chunk).slice(-2000); });
        child.on('error', error => { failed = error; });
        child.once('close', code => {
          clearTimeout(timer); signal.removeEventListener('abort', abort);
          if (signal.aborted) reject(new Error('WATCH_CANCELLED'));
          else if (failed || timedOut || code !== 0) reject(failed ?? new Error(timedOut ? 'WATCH_CAPTURE_TIMEOUT' : `WATCH_CAPTURE_FAILED: ${errors || output.slice(-2000)}`));
          else accept(output);
        });
      });
      signal.throwIfAborted();
      const value = JSON.parse(stdout);
      if (!value.ok) throw new Error('WATCH_CAPTURE_FAILED');
      // These files are generated by our own helper, inside this run's scratch dir.
      const raw = await readFile(value.raw_path);
      const png = await readFile(value.image.path);
      return {raw, png, width: value.width, height: value.height,
        bounds: value.bounds, captured_at: value.captured_at};
    } finally {
      for (const file of await readdir(scratch)) await unlink(join(scratch, file));
    }
  };
}

export class OrbWatch {
  constructor({root = ROOT, capture = createWatchCapture(root), notify = () => {},
    now = Date.now, intervalMs = 2000, startDelayMs = 3000,
    maxDurationMs = 300000, maxFrames = 60, maxBytes = 100 * 1024 * 1024} = {}) {
    Object.assign(this, {root, capture, notify, now, intervalMs, startDelayMs, maxDurationMs, maxFrames, maxBytes});
    this.run = null; this.pending = null; this.closed = false; this.writes = Promise.resolve();
  }
  handles(text) { return COMMANDS.has(text.trim()); }
  active() { return this.run?.status === 'recording'; }
  describe() {
    const r = this.run;
    if (!r) return 'Watch 未开始。发送“开始观察”后，3 秒开始观察显示器 1；发送“停止观察”结束。';
    return `Watch ${this.active() ? '观察中' : '已停止'} · 显示器 1\n已采样 ${r.samples} 次，保留 ${r.frames.length} 帧；模型调用 0 次。`
      + (r.reason ? `\n结束原因：${r.reason}` : '\n发送“停止观察”结束。')
      + `\n记录：${join(r.directory, 'manifest.json')}`;
  }
  async persist() {
    const r = this.run;
    const data = JSON.stringify(r, null, 2);
    const operation = this.writes.then(async () => {
      const temp = join(r.directory, 'manifest.tmp');
      await writeFile(temp, data, 'utf8');
      await rename(temp, join(r.directory, 'manifest.json'));
    });
    this.writes = operation.catch(() => {});
    return operation;
  }
  async start(sessionId) {
    if (this.closed) throw new Error('WATCH_CLOSED');
    if (this.active()) return this.describe();
    await this.pending;
    await this.writes;
    if (this.closed) throw new Error('WATCH_CLOSED');
    const id = randomUUID();
    const directory = resolve(this.root, 'runtime/watch', id);
    await mkdir(directory, {recursive: true});
    this.analyzer = new FrameChangeAnalyzer(); this.geometry = null;
    this.run = {schema: 1, id, session_id: sessionId, directory, status: 'recording',
      started_at: new Date(this.now()).toISOString(), started_ms: this.now(),
      scope: {kind: 'monitor', monitor: 1}, samples: 0, frames: [], bytes: 0,
      model_calls: 0, semantic_analysis: 'not_run', memory_written: false,
      interval_ms: this.intervalMs, max_duration_ms: this.maxDurationMs,
      max_frames: this.maxFrames, max_bytes: this.maxBytes};
    try { await this.persist(); }
    catch (error) { this.run.status = 'stopped'; this.run.reason = '记录写入失败'; throw error; }
    this.deadline = setTimeout(() => { void this.stop('已达 5 分钟上限').catch(() => {}); }, this.maxDurationMs);
    this.deadline.unref?.();
    this.schedule(this.startDelayMs);
    return 'Watch 已开始，3 秒后采样显示器 1（包含其上可见的窗口和 Orb 面板）。请切回要演示的软件。\n每 2 秒本地采样，保留首帧与变化帧；最多 5 分钟、60 帧或 100 MB。发送“停止观察”结束，“观察状态”查看状态。\n当前仅记录画面，不识别点击或输入、不生成步骤、不写入记忆，模型调用为 0。';
  }
  schedule(delay) {
    this.timer = setTimeout(() => { void this.tick(); }, delay);
    this.timer.unref?.();
  }
  async tick() {
    if (!this.active() || this.pending) return;
    clearTimeout(this.timer);
    const r = this.run;
    this.abort = new AbortController();
    this.pending = (async () => {
      try {
        const frame = await this.capture({directory: r.directory, signal: this.abort.signal});
        if (!this.active() || this.run !== r) return;
        r.samples++;
        const geometry = JSON.stringify([frame.bounds, frame.width, frame.height]);
        const change = this.analyzer.analyze(frame.raw, frame.width, frame.height);
        if (!r.frames.length || geometry !== this.geometry || change.change_bbox) {
          if (r.bytes + frame.png.length > this.maxBytes) { r.status = 'stopped'; r.reason = '已达存储上限'; }
          else {
            const file = `frame-${String(r.frames.length + 1).padStart(3, '0')}.png`;
            await writeFile(join(r.directory, file), frame.png, {flag: 'wx'});
            r.frames.push({file, captured_at: frame.captured_at, bounds: frame.bounds,
              width: frame.width, height: frame.height, changed_ratio: change.changed_ratio});
            r.bytes += frame.png.length;
          }
        }
        this.geometry = geometry;
        if (r.frames.length >= this.maxFrames) { r.status = 'stopped'; r.reason = '已达保留帧上限'; }
        if (!this.active()) r.stopped_at = new Date(this.now()).toISOString();
        await this.persist();
      } catch (error) {
        if (this.active()) {
          r.status = 'stopped'; r.reason = '采样或记录失败，请重新开始';
          r.error = String(error.message); r.stopped_at = new Date(this.now()).toISOString();
          await this.persist().catch(() => {});
        }
      }
    })();
    try { await this.pending; }
    finally {
      this.pending = null;
      if (this.active()) this.schedule(this.intervalMs);
      else clearTimeout(this.deadline);
      this.notify(this.describe(), this.run);
    }
  }
  async stop(reason = '用户停止') {
    clearTimeout(this.timer); clearTimeout(this.deadline);
    if (!this.run) return this.describe();
    if (this.active()) {
      this.run.status = 'stopped'; this.run.reason = reason;
      this.run.stopped_at = new Date(this.now()).toISOString();
    }
    this.abort?.abort();
    await this.pending;
    await this.persist();
    this.notify(this.describe(), this.run);
    return this.describe();
  }
  async dispose() { this.closed = true; await this.stop('观察入口已关闭'); }
}

export function installOrbWatch(ctx, runtime, options = {}) {
  const watch = new OrbWatch({...options, notify: (text, run) => {
    if (runtime.sessionId === run.session_id) runtime.block(`watch:${run.id}`, 'assistant', text, false, 'set');
  }});
  let queue = Promise.resolve();
  const control = action => {
    const operation = queue.then(action); queue = operation.catch(() => {}); return operation;
  };
  runtime.observationWatch = {
    handles: text => watch.handles(text),
    control: (text, lassoId) => control(async () => {
      if (lassoId !== undefined) return '请单独发送纯文本观察命令，不附带圈选截图。';
      const command = COMMANDS.get(text.trim());
      if (command === 'status') return watch.describe();
      if (command === 'stop') return watch.stop();
      if (command !== 'start') throw new Error('WATCH_UNKNOWN_COMMAND');
      const registry = runtime.agentRegistry();
      if (runtime.turnRunning || runtime.pendingPrompt || runtime.pending || !registry
        || registry.list().some(row => row.state === 'running')) {
        return '当前有操作任务或待处理交互，请先结束任务，再发送“开始观察”。';
      }
      return watch.start(await runtime.ensureSession());
    }),
    beforePrompt: () => control(async () => { if (watch.active()) await watch.stop('开始新的对话或操作任务'); }),
  };
  const originals = new Map();
  for (const name of ['newSession', 'openSession', 'stopTurn']) {
    if (typeof runtime[name] !== 'function') continue;
    const original = runtime[name]; originals.set(name, original);
    runtime[name] = async function (...args) {
      await control(() => watch.stop('会话切换或 Orb 关闭'));
      return original.apply(this, args);
    };
  }
  // halt is synchronous in Orb. Stop scheduling immediately, without delaying
  // native helper teardown; the pending capture is aborted and then drained.
  const originalHalt = runtime.halt;
  if (typeof originalHalt === 'function') {
    runtime.halt = function (...args) {
      void watch.stop('Orb 已关闭').catch(() => {});
      return originalHalt.apply(this, args);
    };
    originals.set('halt', originalHalt);
  }
  ctx.effect(() => async () => {
    await control(() => watch.dispose());
    for (const [name, original] of originals) runtime[name] = original;
    delete runtime.observationWatch;
  });
  return watch;
}
